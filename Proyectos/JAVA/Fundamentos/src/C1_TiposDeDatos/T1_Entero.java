package C1_TiposDeDatos;

public class T1_Entero {

    public static void main(String[] args) {
        // * ---------------------------
        // * TIPO DE DATO ENTERO EN JAVA
        // * ---------------------------

        // ? Los números enteros representan números
        // ? SIN PARTE DECIMAL: positivos, negativos o cero
        // ? Ej:    75  -140    6800    0

        System.out.println(75);
        System.out.println(-140);
        System.out.println(6800);
        System.out.println(0);

        // ? Java posee cuatro tipos primitivos
        // ? principales para números enteros

        // * byte, short, int, long

        // * ------------------------
        // * TIPO DE DATO ENTERO byte
        // * ------------------------

        // ? Es el tipo entero de menor tamaño

        // * Tamaño:    8bits
        // * Rango:     -128 hasta 127

        // * -------------------------
        // * TIPO DE DATO ENTERO short
        // * -------------------------

        // ? Permite respresentar un rango mayor
        // ? de números enteros que byte

        // * Tamaño:    16bits
        // * Rango:     -32768 hasta 32767

        // * -----------------------
        // * TIPO DE DATO ENTERO int
        // * -----------------------

        // ? Es elk tipo entero de uso general
        // ? más utilizado en Java

        // * Tamaño:    32bits
        // * Rango:     -2147483684 hasta 2147483647

        // * ------------------------
        // * TIPO DE DATO ENTERO long
        // * ------------------------

        // ? Se utiliza cuando necesitamos representar
        // ? números enteros de gran magnitud

        // * Tamaño:    64bits
        // * Rango:     
        // * -9223372036854775808 hasta 9223372036854775807

    }

}