
# * ----------------------
# * OPERADORES ARITMÉTICOS
# * ----------------------

# ? Los operadores aritméticos permiten
# ? realizar operaciones matemáticas con
# ? valores numéricos

# * OPERADOR SUMA +

# ? Permite sumar dos valores numéricos

# * int + int       ->      int
# * int + float     ->      float
# * float + int     ->      float
# * float + float   ->      float

print("\n")
print("Operador Suma: ")
print(4 + 3)        # 7
print(6 + 2.5)      # 8.5
print(2.5 + 6)      # 8.5
print(2.5 + 1.5)    # 4.0

# ? El operador + también puede utilizarse
# ? para concatenar cadenas

# * str + str = str

print("\n")
print("Operador Suma: Concatenación ")
print("Programación " + "Para " + "Todos")
# * Programación Para Todos

# * OPERADOR RESTA -

# ? Permite restar un valor de otro

# * int - int       ->      int
# * int - float     ->      float
# * float - int     ->      float
# * float - float   ->      float

print("\n")
print("Operador Resta: ")
print(10 - 4)       # 6
print(10 - 2.5)     # 7.5
print(8.5 - 3)      # 5.5
print(8.5 - 2.5)    # 6.0


# * OPERADOR MULTIPLICACIÓN *

# ? Permite multiplicar dos valores

# * int * int       ->      int
# * int * float     ->      float
# * float * int     ->      float
# * float * float   ->      float

print("\n")
print("Operador Multiplicación: ")
print(10 * 4)       # 40
print(10 * 2.5)     # 25
print(8.5 * 3)      # 25.5
print(8.5 * 2.5)    # 21.25

# * OPERADOR DIVISIÓN REAL /

# ? Realiza una división normal
# ? El resultado de / es float

# * int / int       ->      float
# * int / float     ->      float
# * float / int     ->      float
# * float / float   ->      float

print("\n")
print("Operador División Real: ")
print(10 / 2)       # 5.0
print(10 / 4.0)     # 2.5
print(8.5 / 2)      # 4.25
print(7.5 / 2.5)    # 3.0

# * OPERADOR DIVISIÓN ENTERA //

# ? Realiza una división y toma el
# ? resultado redondeado hacia abajo

# * int // int       ->      int
# * int // float     ->      float
# * float // int     ->      float
# * float // float   ->      float

print("\n")
print("Operador División Entera: ")
print(10 // 3)       # 3
print(10 // 3.0)     # 3.0
print(10.0 // 3)     # 3.0
print(10.0 // 3.0)   # 3.0

# * OPERADOR MÓDULO %

# ? Devuelve el residuo de una división

# * int % int       ->      int
# * int % float     ->      float
# * float % int     ->      float
# * float % float   ->      float

print("\n")
print("Operador Módulo: ")
print(10 % 3)       # 1
print(10 % 4.0)     # 2.0
print(10.0 % 2)     # 0.0
print(10.0 % 3.0)   # 1.0

# * OPERADOR POTENCIA **

# ? Eleva un número a una 
# ? determinada potencia

# * int ** int       ->      int o float
# * int ** float     ->      float
# * float ** int     ->      float
# * float ** float   ->      float

print("\n")
print("Operador Módulo: ")
print(2 ** 3)       # 8
print(2 ** -1)      # 0.5
print(2 ** 0.5)     # 1.414
print(2.0 ** 5)     # 32.0
print(2.0 ** 3.0)   # 8.0