// ? Permite guardar un valor en una variable
// ? El tipo de dato debe ser compatible
// ? con el valor que se asigna

// * variable = valor;

int estudiantes = 20;
float temperatura = 18.5f;
double distancia = 145.75;
decimal salario = 4250.80m;
char seccion = 'C';
string ciudad = "Oruro";
bool disponible = false;

Console.WriteLine("Operador de Asignación: ");
Console.WriteLine(estudiantes);     // 20
Console.WriteLine(temperatura);     // 18.5
Console.WriteLine(distancia);       // 145.75
Console.WriteLine(salario);         // 4250.80
Console.WriteLine(seccion);         // C
Console.WriteLine(ciudad);          // Oruro
Console.WriteLine(disponible);      // false

