public class T3_Caracter {
    public static void main(String[] args) {
        // * -----------------------------
        // * TIPO DE DATO CARACTER EN JAVA
        // * -----------------------------

        // ? Un caracter representa UN SOLO elemento
        // ? Puede representar:
        // * letra, dígito, símbolo, espacio

        // ? Ej:    'M'     '6'     '&'     ' '

        System.out.println('M');
        System.out.println('6');
        System.out.println('&');

        // * --------------------------
        // * TIPO DE DATO CARACTER char
        // * --------------------------

        // ? Java posee un tipo primitivo
        // ? específico para caracteres

        // ! Los caracteres se escriben
        // ! utilizando comillas SIMPLES

        // * ------------------
        // * CARACTER VS ENTERO
        // * ------------------

        System.out.println('9');
        System.out.println(9);

        // ? Aunque visualmente ambos representan
        // ? un nueve, son datos diferentes

        // * '9'        char
        // *  9         int

    }
}
